#!/usr/bin/env python3
"""Rebuild distributable dictionaries from pinned, local source data."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def big5(char):
    try:
        return char.encode('big5')
    except UnicodeEncodeError:
        return b'\xff\xff'


def character_dictionary():
    source = (ROOT / 'data/upstream/quick-classic.txt').read_text(encoding='utf-8')
    table = source.split('BEGIN_TABLE', 1)[1].split('END_TABLE', 1)[0]
    rows = []
    for line in table.splitlines():
        parts = re.split(r'[ \t]+', line.strip(' \t\r\n'))
        if len(parts) == 3 and re.fullmatch('[a-z]{1,2}', parts[0]):
            code, word, frequency = parts
            rows.append((code, word, int(frequency)))
    rows.sort(key=lambda r: (r[0], -r[2], big5(r[1][0]), ord(r[1][0])))
    version = (ROOT / 'VERSION').read_text().strip()
    header = (
        '# Generated by tools/build_data.py; see THIRD_PARTY.md.\n'
        '# Quick Classic: Roy Hiu-yeung Chan. Freely redistributable without restriction.\n'
        '---\nname: linux_xp_quick\n'
        f'version: "{version}"\nsort: original\nuse_preset_vocabulary: false\n...\n'
    )
    return header + ''.join(f'{word}\t{code}\n' for code, word, _ in rows)


def phrase_index():
    source = (ROOT / 'data/upstream/cixin_quick_index.lua').read_text(encoding='utf-8')
    index = {}
    for line in source.splitlines():
        match = re.fullmatch(r'\s*\[(".*?")\]\s*=\s*\{(.*?)\},?\s*', line)
        if match:
            head = json.loads(match[1])
            words = json.loads('[' + match[2] + ']')
            if len(head) != 1 or any(not w.startswith(head) or len(w) < 2 for w in words):
                raise ValueError(f'Invalid phrase source: {head}')
            index[head] = list(dict.fromkeys(words))
    if not index:
        raise ValueError('No predictions parsed')
    overrides = json.loads((ROOT / 'data/prediction-overrides.json').read_text(encoding='utf-8'))
    for head, words in overrides.items():
        if any(not w.startswith(head) or len(w) < 2 for w in words):
            raise ValueError(f'Invalid override: {head}')
        index[head] = list(dict.fromkeys(words + index.get(head, [])))
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    return (
        '-- Generated by tools/build_data.py. Phrase data: LGPL-3.0; see THIRD_PARTY.md.\n'
        'return {\n' + ''.join(
            f'  [{quote(head)}] = {{{", ".join(map(quote, index[head]))}}},\n'
            for head in sorted(index)
        ) + '}\n'
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check generated files without writing')
    args = parser.parse_args()
    for name, metadata in json.loads((ROOT / 'data/sources.json').read_text()).items():
        actual = hashlib.sha256((ROOT / 'data/upstream' / name).read_bytes()).hexdigest()
        if actual != metadata['sha256']:
            raise SystemExit(f'Upstream checksum mismatch: {name}')
    files = {
        'rime/linux_xp_quick.dict.yaml': character_dictionary(),
        'rime/lua/linux_xp_quick/data.lua': phrase_index(),
    }
    for name, text in files.items():
        target = ROOT / name
        if args.check:
            if not target.exists() or target.read_text(encoding='utf-8') != text:
                raise SystemExit(f'Generated file is out of date: {name}')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding='utf-8')
        print(name)


if __name__ == '__main__':
    main()
